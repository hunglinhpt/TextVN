/// Cấm các từ đơn đang được test ghim hoàn tất hậu tố `-s`/`-e` ở 1st-Tab làm từ đầu
/// của compound trong `en_compounds.txt` (giữ tương thích 100% với các test hiện có).
const RESERVED_FIRST_WORDS: &[&str] = &[
    "develop", "improv", "rele", "lot", "tes", "see", "ebi", "ebit", "kp", "gith", "sort",
];

fn gen_en_compounds() -> Result<usize, String> {
    let path = "data/en_compounds.txt";
    let mut map: BTreeMap<String, u32> = BTreeMap::new();
    for (group, entries) in EN_COMPOUND_GROUPS {
        for &(w, weight) in *entries {
            let clean = w.trim().to_lowercase();
            if clean.is_empty()
                || !clean.contains(' ')
                || !clean.chars().all(|c| c.is_ascii_lowercase() || c == ' ')
                || clean.contains("  ")
            {
                return Err(format!("en_compounds ({group}): mục không hợp lệ `{w}`"));
            }
            let first = clean.split(' ').next().unwrap_or("");
            if RESERVED_FIRST_WORDS.contains(&first) {
                return Err(format!(
                    "en_compounds ({group}): từ đầu `{first}` nằm trong RESERVED_FIRST_WORDS"
                ));
            }
            let cur = map.entry(clean).or_insert(weight);
            if weight > *cur {
                *cur = weight;
            }
        }
    }

    let mut out = String::new();
    out.push_str(
        "# Từ ghép & cụm danh từ tiếng Anh thông dụng — 16 domain (kinh doanh, quản trị,\n",
    );
    out.push_str(
        "# kỹ thuật phần mềm, AI/dữ liệu, Cloud/DevOps/bảo mật, tài chính-kế toán-thuế,\n",
    );
    out.push_str(
        "# ngân hàng-bảo hiểm, nhân sự, marketing-thương mại điện tử, CSKH-QA, sản phẩm-\n",
    );
    out.push_str(
        "# UI/UX, logistics-chuỗi cung ứng-sản xuất, pháp lý-hợp đồng-đấu thầu, bất động\n",
    );
    out.push_str("# sản-xây dựng, y tế, giáo dục-nghiên cứu, giao tiếp công sở).\n");
    out.push_str(
        "# Format: english_compound<TAB>weight. Sinh bởi `cargo xtask gen-vocab` — KHÔNG sửa tay.\n",
    );
    for (w, weight) in &map {
        out.push_str(w);
        out.push('\t');
        out.push_str(&weight.to_string());
        out.push('\n');
    }
    fs::write(path, out).map_err(|e| e.to_string())?;
    println!("en_compounds.txt: {} mục", map.len());
    Ok(map.len())
}

fn check_en_words10k() -> Result<usize, String> {
    let raw =
        fs::read_to_string("data/en_words10k.txt").map_err(|e| format!("en_words10k: {e}"))?;
    let mut n = 0;
    for line in raw.lines() {
        let t = line.trim();
        if t.is_empty() || t.starts_with('#') {
            continue;
        }
        if !t.chars().all(|c| c.is_ascii_lowercase()) || t.len() < 2 {
            return Err(format!("en_words10k.txt: dòng không hợp lệ: {t:?}"));
        }
        n += 1;
    }
    Ok(n)
}

